import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# 1. Load Dataset
url = "https://raw.githubusercontent.com/datasciencedojo/datasets/master/titanic.csv"
df = pd.read_csv(url)

print("ORIGINAL DATASET")
print(df.head())
print("\nDataset Shape:", df.shape)

# 2. Clean Dataset (Task 1)
df = df.drop_duplicates()

df["Age"] = df["Age"].fillna(df["Age"].median())
df["Embarked"] = df["Embarked"].fillna(df["Embarked"].mode()[0])

df["Sex"] = df["Sex"].str.strip().str.capitalize()
df["Embarked"] = df["Embarked"].str.strip().str.upper()

df["Cabin_Known"] = df["Cabin"].notna().astype(int)
df = df.drop(columns=["Cabin"])

print("\nCLEANED DATASET")
print(df.head())

# 3. Dataset Information
print("\nDataset Information:")
df.info()

print("\nMissing Values:")
print(df.isnull().sum())

print("\nDuplicate Records:")
print(df.duplicated().sum())

# 4. Important Statistics
print("\nIMPORTANT STATISTICS")

print("Total Passengers:", len(df))
print("Total Survivors:", df["Survived"].sum())
print("Total Deaths:", (df["Survived"] == 0).sum())

print("Survival Percentage:", round(df["Survived"].mean() * 100, 2), "%")
print("Average Age:", round(df["Age"].mean(), 2))
print("Median Age:", round(df["Age"].median(), 2))
print("Average Fare:", round(df["Fare"].mean(), 2))
print("Median Fare:", round(df["Fare"].median(), 2))

print("\nStatistical Summary:")
print(df.describe())

# 5. Survival Rate by Gender
print("\nSURVIVAL RATE BY GENDER")
print(df.groupby("Sex")["Survived"].mean() * 100)

# 6. Survival Rate by Passenger Class
print("\nSURVIVAL RATE BY PASSENGER CLASS")
print(df.groupby("Pclass")["Survived"].mean() * 100)

# 7. Passengers by Embarkation Port
print("\nPASSENGERS BY EMBARKATION PORT")
print(df["Embarked"].value_counts())

# 8. Chart 1 - Survival Count
sns.countplot(data=df, x="Survived")
plt.title("Survival Count")
plt.xlabel("Survived (0 = No, 1 = Yes)")
plt.ylabel("Number of Passengers")
plt.show()

# 9. Chart 2 - Survival by Gender
sns.barplot(data=df, x="Sex", y="Survived")
plt.title("Survival Rate by Gender")
plt.xlabel("Gender")
plt.ylabel("Survival Rate")
plt.show()

# 10. Chart 3 - Survival by Passenger Class
sns.barplot(data=df, x="Pclass", y="Survived")
plt.title("Survival Rate by Passenger Class")
plt.xlabel("Passenger Class")
plt.ylabel("Survival Rate")
plt.show()

# 11. Chart 4 - Age Distribution
sns.histplot(data=df, x="Age", bins=20)
plt.title("Age Distribution of Passengers")
plt.xlabel("Age")
plt.ylabel("Number of Passengers")
plt.show()

# 12. Chart 5 - Ticket Fare Distribution
sns.boxplot(data=df, x="Pclass", y="Fare")
plt.title("Ticket Fare by Passenger Class")
plt.xlabel("Passenger Class")
plt.ylabel("Ticket Fare")
plt.show()

# 13. Identify Useful Insights
print("\nFIVE USEFUL INSIGHTS")

print("1. Most passengers did not survive the Titanic accident.")

print("2. Female passengers had a higher survival rate than male passengers.")

print("3. First-class passengers had a higher survival rate than third-class passengers.")

print("4. Most passengers were young adults.")

print("5. First-class passengers generally paid higher ticket fares.")

# 14. Save Cleaned Dataset
df.to_csv("titanic_cleaned.csv", index=False)

print("\nCleaned dataset saved successfully!")

